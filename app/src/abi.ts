import { parseAbi } from 'viem';

// Read functions and events used by the dashboard, plus every custom error the vault can revert with,
// so refusals decode to names. Signatures match src/MoneyblocksVault.sol.
export const vaultAbi = parseAbi([
  'function owner() view returns (address)',
  'function targetRatioBps() view returns (uint256)',
  'function approvalThreshold() view returns (uint256)',
  'function blockCount() view returns (uint256)',
  'function paymentCount() view returns (uint256)',
  'function groupsClosed() view returns (uint256)',
  'function troveActive() view returns (bool)',
  'function totalCash() view returns (uint256)',
  'function totalPrincipal() view returns (uint256)',
  'function totalInterest() view returns (uint256)',
  'function overheadPrincipal() view returns (uint256)',
  'function overheadInterest() view returns (uint256)',
  'function overheadCash() view returns (uint256)',
  'function groupPosition() view returns (uint256 coll, uint256 principal, uint256 interest)',
  'function groupCapacity() view returns (uint256)',
  'function moneyblocks(uint256 blockId) view returns (string name, bool exists, bool cross, uint256 cash, uint256 reserved, uint256 debtCap, uint256 principal, uint256 interest, address operator, bool mandateActive, uint64 expiry, uint256 perTxCap, uint256 totalCap, uint256 committed, uint256 spent)',
  'function payments(uint256 paymentId) view returns (uint256 blockId, address to, uint256 amount, bytes32 evidence, uint8 status)',
  'event RecipientSet(uint256 indexed blockId, address indexed to, bool allowed)',
  'error NotOwner()',
  'error NotOperator(uint256 blockId)',
  'error ZeroAmount()',
  'error InvalidMandate()',
  'error BlockNotFound(uint256 blockId)',
  'error BlockNotCross(uint256 blockId)',
  'error MandateRevoked(uint256 blockId)',
  'error MandateExpired(uint256 blockId)',
  'error RecipientNotAllowed(uint256 blockId, address to)',
  'error PerTransactionCapExceeded(uint256 amount, uint256 cap)',
  'error MandateTotalCapExceeded(uint256 amount, uint256 remaining)',
  'error PocketInsufficient(uint256 blockId, uint256 available, uint256 requested)',
  'error BlockDebtCapExceeded(uint256 blockId, uint256 debtAfter, uint256 cap)',
  'error GroupCapacityExceeded(uint256 debtAfter, uint256 capacity)',
  'error GroupNotOpen()',
  'error GroupAlreadyOpen()',
  'error LedgerDirty()',
  'error InterestUnsettled(uint256 blockId, uint256 interestDue, uint256 available)',
  'error RepayExceedsPrincipal(uint256 blockId, uint256 amount, uint256 principal)',
  'error DebtNotCovered(uint256 blockId, uint256 debt, uint256 available)',
  'error PaymentNotPending(uint256 paymentId)',
  'error PendingRewards()',
  'error LedgerMismatch()',
  'error CashMismatch()',
  'error TransferFailed()',
  'error SendFailed()',
  'error GroupStillOpen()',
  'error NoGroupClosed()',
  'error CashReserved(uint256 blockId, uint256 reserved)',
  'error ZeroAddress()',
]);

export const erc20Abi = parseAbi(['function balanceOf(address account) view returns (uint256)']);

export const priceFeedAbi = parseAbi(['function fetchPrice() view returns (uint256)']);
